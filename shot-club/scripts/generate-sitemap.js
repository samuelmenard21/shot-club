// file in public/. App.jsx ends with a catch-all that redirects unknown paths
// to '/', so a stale entry doesn't 404 — it silently becomes a duplicate of the
// homepage, which is worse: Google logs it as a soft-404 / duplicate and it
// drags on crawl trust. Two such entries (/how-many-shots-per-day and
// /10000-shots-app-alternative) were listed here without ever being built.
//
// Keep in sync with the PAGES array in scripts/prerender.js.
