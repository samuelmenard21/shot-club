const __filename = fileURLToPath(import.meta.url)
const __dirname  = dirname(__filename)
const PUBLIC_DIR = join(__dirname, '..', 'public')

function escapeXml(s) {
  return String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;')
}

function buildUrlEntry({ loc, lastmod, changefreq, priority }) {
  const parts = [
    `  <url>`,
    `    <loc>${escapeXml(loc)}</loc>`,
  ]
  if (lastmod)    parts.push(`    <lastmod>${escapeXml(lastmod)}</lastmod>`)
  if (changefreq) parts.push(`    <changefreq>${escapeXml(changefreq)}</changefreq>`)
  if (priority)   parts.push(`    <priority>${escapeXml(priority)}</priority>`)
  parts.push(`  </url>`)
  return parts.join('\n')
}

async function fetchAllClubs(supabase) {
  // Supabase's default row cap is 1000. We paginate to get all 3,002+ clubs.
  const PAGE_SIZE = 1000
  let allClubs = []
  let from = 0

  while (true) {
    const { data, error } = await supabase
      .from('clubs')
      .select('slug, created_at')
      .order('created_at', { ascending: true })
      .range(from, from + PAGE_SIZE - 1)

    if (error) {
      console.error('❌ Supabase query failed:', error.message)
      throw error
    }

    if (!data || data.length === 0) break
    allClubs = allClubs.concat(data)
    if (data.length < PAGE_SIZE) break
    from += PAGE_SIZE
  }

  return allClubs
}

async function main() {
  console.log('📋 Generating club sitemap…')

  const url = process.env.VITE_SUPABASE_URL || process.env.SUPABASE_URL
  const key = process.env.VITE_SUPABASE_ANON_KEY || process.env.SUPABASE_ANON_KEY

  // The static sitemap needs no database access, and the club sitemap is
  // intentionally empty while club pages are noindex. So missing credentials
  // must NOT fail the build — that would take the whole deploy down (and with
  // it the static sitemap) over data we aren't publishing yet.
  let clubs = []
  if (!url || !key) {
    console.warn('⚠️  No Supabase env vars — skipping club lookup.')
    console.warn('   Set VITE_SUPABASE_URL and VITE_SUPABASE_ANON_KEY to include clubs later.')
  } else {
    try {
      const supabase = createClient(url, key, { auth: { persistSession: false } })
      clubs = await fetchAllClubs(supabase)
      console.log(`✅ Fetched ${clubs.length} clubs from Supabase`)
    } catch (e) {
      console.warn(`⚠️  Club lookup failed (${e.message}) — continuing with static pages only.`)
    }
  }

  const today = new Date().toISOString().slice(0, 10)

  // Cloudflare Pages 308-redirects a directory route to its trailing-slash form
  // (/challenges -> /challenges/). Sitemaps must list the final URL. The
  // trackers are real .html files served extensionless, so they take no slash.
  const withSlash = (loc) =>
    loc === '/' || loc.endsWith('-tracker') ? loc : `${loc}/`

  const urls = STATIC_PAGES.map((p) => buildUrlEntry({
    loc: `${SITE_URL}${withSlash(p.loc)}`,
    lastmod: today,
    changefreq: p.changefreq,
    priority: p.priority,
  }))

  // Club pages are noindex until they have real activity (see
  // functions/clubs/[slug].js), so they are deliberately NOT listed — pointing
  // Google at thousands of empty template pages burns crawl budget and invites
  // duplicate-content penalties. When clubs gain traction, push the active ones
  // into `urls` here. A single sitemap holds 50,000 URLs, comfortably more than
  // the ~3,000 clubs, so this stays one file.

  const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.join('\n')}
</urlset>
`

  mkdirSync(PUBLIC_DIR, { recursive: true })
  writeFileSync(join(PUBLIC_DIR, 'sitemap.xml'), sitemap)

  // Remove the old split files so they stop being served (they'd go stale and
  // Search Console would keep reporting on URLs we no longer publish).
  for (const stale of ['sitemap-static.xml', 'sitemap-clubs.xml']) {
    const f = join(PUBLIC_DIR, stale)
    if (existsSync(f)) { rmSync(f); console.log(`🧹 Removed stale ${stale}`) }
  }

  console.log(`✅ Wrote sitemap.xml (${urls.length} URLs; ${clubs.length} clubs held back as noindex)`)
  console.log('📋 Sitemap generation complete')
}

main().catch((err) => {
  console.error('❌ Sitemap generation failed:', err)
  process.exit(1)
})
